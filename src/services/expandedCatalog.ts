// Helper to guarantee 100% deduplication by ID and lower-case name/title
function deduplicate<T extends { id: string }>(items: T[], keyFn: (item: T) => string): T[] {
  const seenKeys = new Set<string>();
  const seenIds = new Set<string>();
  const result: T[] = [];

  for (const item of items) {
    const key = keyFn(item).trim().toLowerCase();
    if (!seenKeys.has(key) && !seenIds.has(item.id)) {
      seenKeys.add(key);
      seenIds.add(item.id);
      result.push(item);
    }
  }

  return result;
}

